    parser.add_argument(
        "--train",
        action="store_true",
        help=(
            "Train LambdaMART from "
            "stored ranking examples."
        ),
    )

    args = parser.parse_args()

    if args.train:

        result = train_ranker()

        print(
            json.dumps(
                result,
                indent=2,
            )
        )

    else:

        print(
            "ResolveIQ ranking-learning module loaded."
        )

        print(
            f"Examples: {EXAMPLES_PATH}"
        )

