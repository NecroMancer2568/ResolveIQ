"""
ResolveIQ - Resolution Ranking Learning

Converts human review / historical resolution feedback into
ranking-training examples and trains a LambdaMART resolution ranker.

Learning flow:

    ResolutionPipeline
          |
          v
    Retrieved candidates
          |
          v
      Human review
       /       \
   approved   rejected
       |
       v
  Ranking examples
       |
       v
  Quality filtering
       |
       v
    LambdaMART
       |
       v
resolution_ranker.txt

The current ResolveIQ bootstrap dataset uses the candidate-list schema:

{
    "query": "...",
    "resolution": "...",
    "candidates": [
        {
            "document_id": "...",
            "label": 1,
            "query_similarity": ...,
            "resolution_similarity": ...,
            "combined_similarity": ...,
            "category_match": ...,
            "source_match": ...,
            "authority_score": ...,
            "historical_supervision_weight": ...,
            "approval_signal": ...,
            "success_signal": ...,
            "edit_penalty": ...,
            "candidate_quality": ...
        }
    ],
    "supervision": {
        "weight": ...
    }
}

The learner also retains backward compatibility with the older
positive_features / negative_features schema.

Important design principles:

1. Never treat every retrieved document as equally useful.
2. Approved evidence becomes positive evidence.
3. Retrieved-but-unused evidence becomes hard negatives.
4. Rejected resolutions do NOT automatically make every retrieved
   document negative.
5. Agent edits reduce confidence in the original ranking.
6. Low-quality / ambiguous feedback is excluded from training.
7. Ranking groups contain all candidates for a query.
8. Resolution-aware features are learned directly by LambdaMART.
"""

from __future__ import annotations

import hashlib
import json
import math
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np


