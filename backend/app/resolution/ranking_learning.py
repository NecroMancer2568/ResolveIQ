# Data structures
# ============================================================

@dataclass
class RankingExample:
    example_id: str

    query: str
    context: dict[str, Any]

    positive_id: str
    negative_id: str

    positive_features: dict[str, float]
    negative_features: dict[str, float]

    label: int
    weight: float

    feedback_decision: str
    rating: int | None

    edited: bool
    edit_distance: float

    reason: str | None

    created_at: str


# ============================================================
# Utility functions
# ============================================================

def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def clamp(
    value: float,
    low: float = 0.0,
    high: float = 1.0,
) -> float:
    return max(low, min(high, float(value)))


def normalize_text(text: str) -> str:
    return " ".join(
        str(text or "")
        .lower()
        .strip()
        .split()
    )


def stable_id(*values: Any) -> str:
    payload = "||".join(
        normalize_text(str(value))
        for value in values
    )

    return hashlib.sha256(
        payload.encode("utf-8")
    ).hexdigest()[:20]


def safe_float(
    value: Any,
    default: float = 0.0,
) -> float:
    try:
        value = float(value)

        if not math.isfinite(value):
            return default

        return value

    except (TypeError, ValueError):
        return default


# ============================================================
# Edit measurement
# ============================================================

def normalized_edit_distance(
    original: str,
    edited: str,
) -> float:
    """
    Approximate normalized Levenshtein distance.

    0.0 = no edit
    1.0 = very large edit

    Uses difflib rather than an additional dependency.
    """

    import difflib

    original = normalize_text(original)
    edited = normalize_text(edited)

    if original == edited:
        return 0.0

    if not original or not edited:
        return 1.0

    similarity = difflib.SequenceMatcher(
        None,
        original,
        edited,
    ).ratio()

    return clamp(1.0 - similarity)


# ============================================================
# Feedback quality
# ============================================================

def feedback_quality(
    decision: str,
    rating: int | None,
    edited: bool,
    edit_distance: float,
) -> float:
    """
    Calculate confidence in human feedback.

    Strong approval:
        approved + 5 + no edit -> 1.0

    Weak approval:
        approved + 3 + heavy edit -> lower weight

    Rejection:
        useful as negative feedback, but deliberately weighted
        lower than strong approval because rejection can happen
        for reasons unrelated to retrieval.
    """

    decision = normalize_text(decision)

    rating_value = (
        clamp(rating / 5.0)
        if rating is not None
        else 0.6
    )

    if decision == "approved":

        quality = 0.65 + 0.35 * rating_value

        if edited:
            quality *= max(
                0.25,
                1.0 - 0.70 * edit_distance,
            )

        return clamp(quality)

    if decision == "rejected":

        quality = 0.55

        if rating is not None:
            quality *= (
                0.7
                + 0.3 * (1.0 - rating_value)
            )

        return clamp(quality)

    return 0.0


# ============================================================
# Candidate feature extraction
# ============================================================

def extract_features(
    query: str,
    candidate: dict[str, Any],
) -> dict[str, float]:
    """
    Legacy candidate feature extraction.

    Kept for compatibility with the original ResolveIQ
    human-feedback pipeline.
    """

    metadata = candidate.get(
        "metadata",
        {},
    ) or {}

    content = str(
        candidate.get(
            "content",
            "",
        )
    )

    retrieval_score = safe_float(
        candidate.get("score", 0.0)
    )

    context_match = safe_float(
        metadata.get(
            "context_match",
            0.5,
        ),
        0.5,
    )

    authority = safe_float(
        metadata.get(
            "authority",
            0.5,
        ),
        0.5,
    )

    freshness = safe_float(
        metadata.get(
            "freshness",
            0.5,
        ),
        0.5,
    )

    historical_success = safe_float(
        metadata.get(
            "historical_success",
            0.5,
        ),
        0.5,
    )

    resolution_frequency = safe_float(
        metadata.get(
            "resolution_frequency",
            0.0,
        )
    )

    source_quality = safe_float(
        metadata.get(
            "source_quality",
            authority,
        ),
        authority,
    )

    query_tokens = set(
        normalize_text(query).split()
    )

    candidate_tokens = set(
        normalize_text(content).split()
    )

    if query_tokens and candidate_tokens:

        overlap = (
            len(query_tokens & candidate_tokens)
            / max(len(query_tokens), 1)
        )

    else:
        overlap = 0.0

    return {
        "retrieval_score": clamp(
            retrieval_score
        ),
        "context_match": clamp(
            context_match
        ),
        "authority": clamp(
            authority
        ),
        "freshness": clamp(
            freshness
        ),
        "historical_success": clamp(
            historical_success
        ),
        "resolution_frequency": clamp(
            resolution_frequency
        ),
        "source_quality": clamp(
            source_quality
        ),
        "query_length": clamp(
            len(query) / 500.0
        ),
        "candidate_length": clamp(
            len(content) / 5000.0
        ),
        "query_candidate_similarity": clamp(
            overlap
        ),
    }


